"""Generate phase-limited transition fixtures after every revised gate passes.

Run: proto/.venv/bin/python proto/dump_spectral_transition_fixtures.py
"""

from pathlib import Path
import sys

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import spectral_parity as sp  # noqa: E402
import spectral_transition as st  # noqa: E402


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "test" / "spectral_transition_fixtures.h"


def arr(values):
    return ", ".join(f"{float(x):.17g}" for x in np.ravel(values))


def main():
    metrics = st.run_all_gates()  # fixture export is gated, never hand-copied
    fs, M, L = sp.FS, sp.DESIGN_FFT, sp.MINIMUM_TAPS
    f = np.fft.rfftfreq(M, 1.0 / fs)
    targets = st.make_targets(fs, M)
    current = st.causal_log_endpoint(f, targets["low_shelf40"], 40.0,
                                     fs, M, L)
    target = st.causal_log_endpoint(f, targets["notch54"], 6.0,
                                    fs, M, L)
    admission = st.admit_one_hop(current, target, st.ADMISSION_PHASE_LIMIT)
    next_endpoint = admission.endpoint

    # Compact activated-bank time-domain fixture; static full-capacity FIR
    # layout remains pinned separately by spectral_fir_fixtures.h.
    rng = np.random.default_rng(0x7A17)
    fixture_l = 8 * sp.PARTITION
    old = rng.normal(0.0, 0.03, fixture_l) * np.exp(-np.arange(fixture_l) / 80.0)
    new = rng.normal(0.0, 0.03, fixture_l) * np.exp(-np.arange(fixture_l) / 70.0)
    start, hop = 12 * sp.PARTITION, 64
    x = np.r_[rng.normal(0.0, 0.2, start + hop + 97), np.zeros(fixture_l - 1)]
    old_y = sp.direct_fir(x, old)
    new_y = sp.direct_fir(x, new)
    q = np.arange(len(x)) - start
    weight = np.where(q < 0, 0.0, np.where(q >= hop, 1.0,
                      0.5 - 0.5 * np.cos(np.pi * q / hop)))
    expected = (1.0 - weight) * old_y + weight * new_y

    finite = metrics["test 3 finite-FIR admission"]
    text = f"""// Generated by proto/dump_spectral_transition_fixtures.py. DO NOT EDIT.
// Scope: verified phase-limited transition math/history only. Product CPU,
// host integration, and soothe sonic equivalence are not established.
#pragma once
#include <array>
#include <cstddef>

namespace spectral_transition_fixtures {{
inline constexpr std::size_t kDesignFft = {M};
inline constexpr std::size_t kTaps = {L};
inline constexpr std::size_t kPositiveBins = {M // 2 + 1};
inline constexpr std::size_t kPartition = {sp.PARTITION};
inline constexpr double kSampleRate = {fs:.17g};
inline constexpr double kPhiLimit = {st.PHI_LIMIT:.17g};
inline constexpr double kPhaseErrorReserve = {st.PHASE_ERROR_MARGIN:.17g};
inline constexpr double kAdmissionPhaseLimit = {st.ADMISSION_PHASE_LIMIT:.17g};
inline constexpr double kFixtureGridDistance = {admission.grid_phase_distance:.17g};
inline constexpr double kFixtureAlpha = {admission.alpha:.17g};
inline constexpr double kCurrentEffectiveCapDb = {current.effective_cap_db:.17g};
inline constexpr double kNextEffectiveCapDb = {next_endpoint.effective_cap_db:.17g};
inline constexpr double kVerifiedPhaseMaxRad = {finite['phase_rad']:.17g};
inline constexpr double kVerifiedAllTCapMaxDb = {finite['all_t_cap_db']:.17g};

inline constexpr std::array<double, kPositiveBins> kCurrentReductionDb{{{{ {arr(current.reduction_db)} }}}};
inline constexpr std::array<double, kPositiveBins> kTargetReductionDb{{{{ {arr(target.reduction_db)} }}}};
inline constexpr std::array<double, kPositiveBins> kNextReductionDb{{{{ {arr(next_endpoint.reduction_db)} }}}};
inline constexpr std::array<double, kTaps> kNextTaps{{{{ {arr(next_endpoint.taps)} }}}};

inline constexpr std::size_t kHistoryTaps = {fixture_l};
inline constexpr std::size_t kHistorySamples = {len(x)};
inline constexpr std::size_t kTransitionStart = {start};
inline constexpr std::size_t kTransitionHop = {hop};
inline constexpr std::array<double, kHistoryTaps> kHistoryOldTaps{{{{ {arr(old)} }}}};
inline constexpr std::array<double, kHistoryTaps> kHistoryNewTaps{{{{ {arr(new)} }}}};
inline constexpr std::array<double, kHistorySamples> kHistoryInput{{{{ {arr(x)} }}}};
inline constexpr std::array<double, kHistorySamples> kHistoryExpected{{{{ {arr(expected)} }}}};
}} // namespace spectral_transition_fixtures
"""
    OUTPUT.write_text(text)
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
