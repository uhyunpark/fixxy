"""Generate sidechain detector, audio and monitor fixtures after numeric gates.

Inputs are float32-rounded; outputs and detector targets are float64. Existing
fixtures/tolerances are untouched. Run from repository root.
"""
from pathlib import Path

import numpy as np

import spectral_sidechain as sc


def numbers(values):
    return ',\n    '.join(f'{float(v):.17g}' for v in np.ravel(values))


def main():
    sc.run_all(render_wavs=False)
    length = 1536
    main, key = (v.astype(np.float32).astype(float) for v in sc.probes(length))
    outputs = {}
    processors = {}
    for name, source, detector, params, mode, enabled, events, connections in [
            ('Soft', main, key, sc.hw.Params(), 0, True, None, None),
            ('Hard', main, key, sc.hw.Params(), 1, True, None, None),
            ('MonoKeyMs', main, key[:1], sc.hw.Params(ms_mode=True, link_pct=0), 1, True, None, None),
            ('StereoKeyMono', main[:1], key, sc.hw.Params(), 1, True, None, None),
            ('Missing', main, None, sc.hw.Params(), 0, True, None, None),
            ('Switch', main, key, sc.hw.Params(), 0, False,
             {768: (True, 1), 1280: (False, 0)}, {512: 0, 768: 1, 1024: 2})]:
        outputs[name], processors[name] = sc.render(
            source, detector, params, mode, enabled, events, connections,
            chunks=(17, 129, 1, 480))

    # Freeze per-bin pre-ballistics target for fully covered frame4 (hop1280).
    targets, gains = {}, {}
    for name in ('Soft', 'Hard'):
        proc = processors[name]
        state = np.zeros(sc.N//2+1)
        for frame, detector in enumerate(proc.detectors):
            g, state, y, target = sc.scalar_gain_oracle(
                np.max(detector, axis=0), proc.cores[0], 0 if name == 'Soft' else 1,
                True, state, np.zeros_like(state) if frame == 0 else y)
            assert np.max(np.abs(g-proc.gains[frame][0])) < 1e-10
            if frame == 4:
                targets[name], gains[name] = target, g

    physical = key.copy()
    physical[:, 512:768] = 0
    physical[1, 768:1024] = physical[0, 768:1024]
    delayed_key = sc.aligned_key(physical, 2, length)
    dry = np.pad(main, ((0, 0), (sc.N, 0)))
    monitor_events = {1050: (False, True, True), 1150: (True, True, True),
                      1500: (False, False, True), 1900: (False, False, False)}
    monitor, _ = sc.monitor_mix(dry, outputs['Switch'], delayed_key, events=monitor_events)
    arrays = [('kMain', main), ('kKey', key)]
    arrays.extend((f'k{name}', audio) for name, audio in outputs.items())
    arrays.extend([(f'k{name}TargetFrame4', value) for name, value in targets.items()])
    arrays.extend([(f'k{name}GainFrame4', value) for name, value in gains.items()])
    arrays.extend([('kAlignedKey', delayed_key), ('kMonitor', monitor)])
    text = f'''// Generated by proto/dump_spectral_sidechain_fixtures.py. DO NOT EDIT.
// Our external-sidechain approximation on unchanged N1024/H256 legacy WOLA.
// All audio arrays are channel-major; leading latency zeros are included.
#pragma once
#include <array>
#include <cstddef>

namespace spectralsidechainfix {{
inline constexpr double kSampleRate = 48000.;
inline constexpr int kFftSize = {sc.N};
inline constexpr int kHop = {sc.HOP};
inline constexpr int kLatency = {sc.N};
inline constexpr std::size_t kInputLength = {length};
inline constexpr std::size_t kOutputLength = {length+sc.N};
inline constexpr int kTargetFrameIndex = 4; // zero-based, completes at sample1280
inline constexpr int kMonitorRampSamples = 240;
inline constexpr double kMonitorMix = .37;
inline constexpr double kMonitorOutGain = .8;
inline constexpr double kMonitorWetGain = 1.4;
// Soft/Hard: stereo main + stereo key; default Params, SC enabled.
// MonoKeyMs: stereo M/S main, mono key=key channel0, linkPct=0, Hard.
// StereoKeyMono: mono main=main channel0, stereo key, default Params, Hard.
// Missing: stereo main, no key, Soft, SC enabled (identity delayed by N).
// Switch: default Params; initially internal Soft. Input control boundaries:
//   sample768 -> external Hard; sample1280 -> internal Soft (retained state).
// Connection events BEFORE input sample512 -> 0ch; 768 -> 1ch; 1024 -> 2ch.
// Initially 2ch key, samples after kInputLength are zero but remain connected.
// Monitor starts Normal; events BEFORE output sample1050 -> SC listen+Delta;
//   1150 -> Bypass+SC listen+Delta; 1500 -> Delta; 1900 -> Normal.
// All four monitor changes use 240-sample linear route-weight ramp, first
// event sample advances 1/240. Retarget starts at current route weights.
// AlignedKey maps per-sample connected key: missing=silence, mono=duplicate.
'''
    for name, value in arrays:
        text += f'\ninline constexpr std::array<double, {np.size(value)}> {name}{{\n    {numbers(value)}\n}};\n'
    text += '} // namespace spectralsidechainfix\n'
    output = Path(__file__).resolve().parents[1]/'test/spectral_sidechain_fixtures.h'
    output.write_text(text)
    print(f'wrote {output} ({output.stat().st_size} bytes)')


if __name__ == '__main__':
    main()
