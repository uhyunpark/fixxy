"""Generate small verified control/WOLA probes; run from repository root."""
from pathlib import Path
import numpy as np
import spectral_cap_wola as cw


def array(name, values, kind="double"):
    values = np.ravel(values)
    numbers = ", ".join(str(int(v)) if kind == "int" else f"{float(v):.17g}" for v in values)
    return f"inline constexpr std::array<{kind}, {len(values)}> {name}{{{{{numbers}}}}};\n"


def main():
    cw.run_all()
    header = """// Generated by proto/dump_spectral_cap_fixtures.py. Do not edit.
// Frame-gain policy only; retained overlap-add has no sample attenuation bound.
#pragma once
#include <array>
namespace spectralcapfix {
constexpr double kSampleRate = 48000.;
constexpr int kHop = 256, kFftSize = 1024, kInputLength = 16384;
constexpr double kLegacyBound = 129.341082406575;
// Scalar rows: initial y=110, s=120; aA=.9, aR=.999; demand=100.
// Each row: requested, effective cap, published/stored y, retained s, gain, bypass.
"""
    cap, y, s, rows = cw.Cap(48000., 24.), 110., 120., []
    for request in [3.]*8+[17.]*8+[0.]*8+[24.]*80+[6.]*8:
        c = cap.step(request)
        demand = min(100., request) if request < 24 else 100.
        y, s = cw.scalar_step(demand, y, s, .9, .999, c, cap.bypass)
        rows.append([request, c, y, s, 10**(-y/20), int(cap.bypass)])
    header += array("kScalarRows", rows)
    indices = [1024, 2048, 8191, 9216, 11264, 14080, 15525, 16383, 17407]
    frames, bins = [30, 31, 32, 42, 50, 56, 63, 67], [16, 160, 192]
    events = {8193: 3., 11001: 17., 13003: 0., 14501: 24.}
    header += array("kProbeSamples", indices, "int")
    header += array("kProbeFrames", frames, "int")+array("kProbeBins", bins, "int")
    header += array("kEventSamples", list(events), "int")+array("kEventCaps", list(events.values()))
    header += """// WOLA input: source() analytic sums computed in double, then cast to float.
// Promote those float carrier samples to double BEFORE the Python reference render.
// L=.30*sin(2*pi*7500*n/fs)+.03*sin(2*pi*731*n/fs)
// R=.17*sin(2*pi*9000*n/fs)-.05*sin(2*pi*731*n/fs)
// Params: depth10/detail10/attack1ms/release1000ms/tiltDetail1/link0/initialOff.
// Audio flatten: [lane][sample probe]. Reduction flatten: [frame][lane][bin].
"""
    source = cw.source().astype(np.float32).astype(float)
    for ms in (False, True):
        for mode in (0, 1):
            p = cw.hw.Params(depth=10., detail=10., attack_ms=1., release_ms=1000.,
                             tilt_detail=1., link_pct=0., ms_mode=ms)
            y, processor = cw.render(source, p=p, mode=mode, cap_events=events)
            name = ("Ms" if ms else "Lr")+("Hard" if mode else "Soft")
            header += array("k"+name+"Audio", y[:, indices])
            reduction = np.asarray(processor.reductions)[frames][:, :, bins]
            header += array("k"+name+"Reduction", reduction)
            header += array("k"+name+"Caps", np.asarray(processor.caps)[frames])
    header += "} // namespace spectralcapfix\n"
    target = Path("test/spectral_cap_fixtures.h")
    target.write_text(header)
    print(f"wrote {target} ({target.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
