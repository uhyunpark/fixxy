"""Dump reference fixtures from the VERIFIED matched_kernel proto into a C++
header consumed by test/matched_kernel_test.cpp. This is the numeric bridge:
the C++ port must reproduce these exact coefficients (1e-12 rel) and magnitudes
(1e-9 dB), or it does not match the proto.

Run from repo root:  ./proto/.venv/bin/python proto/dump_matched_fixtures.py
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from matched_kernel import ivantsov_2nd, ivantsov_tilt, normal_form_dispatch  # noqa: E402
from matched_filters import matched_mag_db  # noqa: E402

SIGMA = 2.0283139124815617  # proto test2 recommended sigma (grid index 38)

# svfcoeffs::Type ordinals (BandResponse.h): keep in lockstep with the enum.
ORD = {"bell": 0, "low_shelf": 1, "high_shelf": 2, "tilt": 3, "notch": 4, "bandpass": 5}

# (type, fs, f0, Q, gainDb) — spans every matched type, gains +-{6,12}, Q in
# {0.5,0.7071,2,6}, f0 in {100,1k,5k,10k,15k}, fs in {44100,48000,96000}, the
# tilt path, and >=2 real-pole-branch cases (the Q=0.1 high-gain rows).
CONFIGS = [
    ("bell",       44100.0,  1000.0, 2.0,     6.0),
    ("bell",       48000.0,  5000.0, 0.7071, -12.0),
    ("bell",       96000.0, 10000.0, 6.0,    12.0),
    ("bell",       44100.0, 15000.0, 0.5,     6.0),
    ("low_shelf",  44100.0,   100.0, 0.7071,  6.0),
    ("low_shelf",  48000.0,  1000.0, 2.0,    -6.0),
    ("low_shelf",  96000.0,  5000.0, 0.5,    12.0),
    ("high_shelf", 44100.0, 10000.0, 0.7071,  6.0),
    ("high_shelf", 48000.0,  5000.0, 2.0,   -12.0),
    ("high_shelf", 96000.0, 15000.0, 6.0,     6.0),
    ("tilt",       44100.0,  1000.0, 0.7071, 12.0),
    ("tilt",       48000.0,  1000.0, 0.7071, -6.0),
    ("tilt",       96000.0,  5000.0, 2.0,    12.0),
    ("notch",      44100.0,   500.0, 6.0,     0.0),
    ("notch",      48000.0, 15000.0, 0.5,     0.0),
    ("notch",      96000.0,  1000.0, 2.0,     0.0),
    ("bandpass",   44100.0,  2000.0, 2.0,     0.0),
    ("bandpass",   48000.0, 10000.0, 6.0,     0.0),
    ("bandpass",   96000.0,   100.0, 0.7071,  0.0),
    # real-pole-branch cases (heavy damping, low f0, big gain -> a1^2 >= 4a2):
    ("low_shelf",  44100.0,   100.0, 0.1,   -24.0),
    ("bell",       48000.0,   100.0, 0.1,   -24.0),
]

MAG_FREQS = [50.0, 100.0, 500.0, 1000.0, 2000.0, 5000.0, 10000.0, 15000.0, 20000.0]


def coeffs_for(bt, fs, f0, Q, g):
    if bt == "tilt":
        return ivantsov_tilt(fs, f0, Q, g, SIGMA)
    return ivantsov_2nd(bt, fs, f0, Q, g, SIGMA)


def main():
    lines = []
    lines.append("// AUTO-GENERATED by proto/dump_matched_fixtures.py — DO NOT EDIT.")
    lines.append("// Reference coefficients + magnitudes from the VERIFIED proto")
    lines.append("// (proto/matched_kernel.py) at sigma = %.17g.\n" % SIGMA)
    lines.append("#pragma once")
    lines.append("#include <array>\n")
    lines.append("namespace matchedfix {\n")
    lines.append("struct MagSample { double f; double magDb; };")
    lines.append("struct Fixture {")
    lines.append("    const char* name;")
    lines.append("    int typeOrdinal;   // svfcoeffs::Type")
    lines.append("    double fs, f0, q, gainDb;")
    lines.append("    double b0, b1, b2, a1, a2;")
    lines.append("    bool branchIsComplex;")
    lines.append("    int nMag;")
    lines.append("    std::array<MagSample, 9> mag;")
    lines.append("};\n")

    n_real = 0
    n_tilt = 0
    entries = []
    for bt, fs, f0, Q, g in CONFIGS:
        b0, b1, b2, a1, a2 = coeffs_for(bt, fs, f0, Q, g)
        disc = a1 * a1 - 4.0 * a2
        # mirror normal_form_dispatch's boundary perturbation for the branch flag
        kind, *_ = normal_form_dispatch(b0, b1, b2, a1, a2)
        is_complex = kind == "complex"
        n_real += kind == "real"
        n_tilt += bt == "tilt"

        freqs = [f for f in MAG_FREQS if f < fs * 0.5 * 0.98]
        mags = matched_mag_db((b0, b1, b2, a1, a2), np.array(freqs), fs)
        magpairs = ", ".join("{%.17g, %.17g}" % (f, m) for f, m in zip(freqs, mags))
        # pad the array literal to 9 entries
        pad = 9 - len(freqs)
        if pad:
            magpairs += ", " + ", ".join("{0.0, 0.0}" for _ in range(pad))

        name = "%s fs=%g f0=%g Q=%g g=%+g" % (bt, fs, f0, Q, g)
        entries.append(
            '    {"%s", %d, %.17g, %.17g, %.17g, %.17g,\n'
            "     %.17g, %.17g, %.17g, %.17g, %.17g,\n"
            "     %s, %d, {{%s}}}," % (
                name, ORD[bt], fs, f0, Q, g,
                b0, b1, b2, a1, a2,
                "true" if is_complex else "false", len(freqs), magpairs))

    assert n_real >= 2, "need >=2 real-pole-branch cases, got %d" % n_real
    assert n_tilt >= 1, "need the tilt path"

    lines.append("inline constexpr double kSigma = %.17g;\n" % SIGMA)
    lines.append("inline const Fixture kFixtures[] = {")
    lines.extend(entries)
    lines.append("};")
    lines.append("inline constexpr int kNumFixtures = %d;" % len(entries))
    lines.append("\n}  // namespace matchedfix")

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "..", "test", "matched_kernel_fixtures.h")
    out = os.path.normpath(out)
    with open(out, "w") as fp:
        fp.write("\n".join(lines) + "\n")
    print("Wrote %s: %d fixtures (%d real-branch, %d tilt)" %
          (out, len(entries), n_real, n_tilt))


if __name__ == "__main__":
    main()
