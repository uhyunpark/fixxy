"""Generate verified static spectral FIR fixtures for the C++ primitive port.

This dump intentionally contains NO IR-transition or dynamic-engine fixture.
It runs only the independently passing static synthesis and causal convolution
gates from spectral_parity.py, then emits test/spectral_fir_fixtures.h.

Run: proto/.venv/bin/python proto/dump_spectral_fir_fixtures.py
"""

from pathlib import Path
import sys

import numpy as np
from scipy import signal

sys.path.insert(0, str(Path(__file__).resolve().parent))
import spectral_parity as sp  # noqa: E402


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "test" / "spectral_fir_fixtures.h"


def array(values):
    return ", ".join(f"{float(x):.17g}" for x in np.ravel(values))


def make_fixtures():
    renderer_metrics = sp.test_renderer()
    synthesis_metrics = sp.test_synthesis()

    # Compact indexing fixture, including every required partition boundary.
    rng = np.random.default_rng(0x5F17)
    P, L = sp.PARTITION, 4 * sp.PARTITION
    h = rng.normal(0.0, 0.025, L) * np.exp(-np.arange(L) / 70.0)
    for index, value in ((P - 1, 0.17), (P, -0.21), (2 * P - 1, 0.13),
                         (2 * P, -0.11), (L - 1, 0.09)):
        h[index] = value
    x = rng.normal(0.0, 0.2, 3 * P + 19)
    expected = signal.lfilter(h, [1.0], x)

    # One full-capacity min-phase synthesis fixture. C++ receives the target on
    # the exact positive design bins and must reproduce all L causal taps.
    f = np.fft.rfftfreq(sp.DESIGN_FFT, 1.0 / sp.FS)
    reduction = (24.0 * np.exp(-0.5 * ((f - 3000.0) / (54.0 / 2.355)) ** 2)
                 + 8.0 * np.exp(-0.5 * ((f - 440.0) / (120.0 / 2.355)) ** 2))
    reduction = np.clip(reduction, 0.0, sp.MAX_REDUCTION_DB)
    taps, full, _ = sp.minimum_phase_fir(
        f, reduction, sp.FS, sp.DESIGN_FFT, sp.MINIMUM_TAPS, True)
    tail_fraction = np.sum(full[sp.MINIMUM_TAPS:] ** 2) / np.sum(full ** 2)

    # Pin the exact rfft layout/scaling for partition 0 and 1. numpy forward FFT
    # is unnormalized; inverse divides by 2P.
    kernel = sp.FirKernel(taps)
    spectra = kernel.spectra[:2]
    return renderer_metrics, synthesis_metrics, h, x, expected, reduction, taps, spectra, tail_fraction


def main():
    (renderer, synthesis, h, x, expected, reduction, taps, spectra,
     tail_fraction) = make_fixtures()
    text = f"""// Generated by proto/dump_spectral_fir_fixtures.py. DO NOT EDIT.
// Scope: verified STATIC FIR synthesis and causal renderer primitives only.
// Transitions/dynamic control are deliberately absent (cap-safe policy pending).
// FFT convention: real FFT length 2*P=128, forward unnormalized, inverse /128;
// bins are k=0..P as separate real/imag arrays. Input spectra ring capacity J+1.
#pragma once
#include <array>
#include <cstddef>

namespace spectral_fir_fixtures {{
inline constexpr std::size_t kDesignFft = {sp.DESIGN_FFT};
inline constexpr std::size_t kMinimumTaps = {sp.MINIMUM_TAPS};
inline constexpr std::size_t kPartition = {sp.PARTITION};
inline constexpr std::size_t kPartitions = {sp.MINIMUM_TAPS // sp.PARTITION};
inline constexpr std::size_t kInputSpectrumCapacity = kPartitions + 1;
inline constexpr std::size_t kPartitionFft = 2 * kPartition;
inline constexpr std::size_t kLinearDelay = {sp.LINEAR_DELAY};
inline constexpr std::size_t kLinearTaps = {sp.LINEAR_TAPS};
inline constexpr double kSampleRate = {sp.FS:.17g};
inline constexpr double kMaxReductionDb = {sp.MAX_REDUCTION_DB:.17g};

inline constexpr double kVerifiedRendererMaxError = {max(renderer.values()):.17g};
inline constexpr double kVerifiedFullGridRelativeError = {synthesis['full_grid_relative']:.17g};
inline constexpr double kVerifiedDenseMagnitudeErrorDb = {synthesis['dense_magnitude_db']:.17g};
inline constexpr double kVerifiedEndpointCapOvershootDb = {synthesis['endpoint_cap_overshoot_db']:.17g};
inline constexpr double kFixtureTailEnergyFraction = {tail_fraction:.17g};

inline constexpr std::array<double, {len(h)}> kRendererTaps{{{{ {array(h)} }}}};
inline constexpr std::array<double, {len(x)}> kRendererInput{{{{ {array(x)} }}}};
inline constexpr std::array<double, {len(expected)}> kRendererExpected{{{{ {array(expected)} }}}};

inline constexpr std::array<double, {len(reduction)}> kTargetReductionDb{{{{ {array(reduction)} }}}};
inline constexpr std::array<double, {len(taps)}> kMinimumPhaseTaps{{{{ {array(taps)} }}}};
inline constexpr std::array<double, {spectra.shape[1]}> kPartition0Real{{{{ {array(spectra[0].real)} }}}};
inline constexpr std::array<double, {spectra.shape[1]}> kPartition0Imag{{{{ {array(spectra[0].imag)} }}}};
inline constexpr std::array<double, {spectra.shape[1]}> kPartition1Real{{{{ {array(spectra[1].real)} }}}};
inline constexpr std::array<double, {spectra.shape[1]}> kPartition1Imag{{{{ {array(spectra[1].imag)} }}}};
}} // namespace spectral_fir_fixtures
"""
    OUTPUT.write_text(text)
    print(f"static renderer gate max={max(renderer.values()):.12g}")
    print(f"synthesis dense max={synthesis['dense_magnitude_db']:.12g} dB")
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
