"""Regenerate scoped additive-Hard/current-WOLA C++ fixtures.

Run only after spectral_hard_wola.run_all passes in this same process. Outputs
include the 1024-sample reported latency. This does not authorize FIR, new-model
controls, or soothe-equivalence claims.
"""
from pathlib import Path
import sys
import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
import spectral_hard_wola as hw


def numbers(values):
    return ",\n    ".join(f"{float(v):.17g}" for v in np.ravel(values))


def main():
    hw.run_all(render_wavs=False)
    fs, length = 48000.0, 2304
    t = np.arange(length)/fs
    rng = np.random.default_rng(20260922)
    source = np.asarray([
        .18*np.sin(2*np.pi*3000*t)+.06*np.sin(2*np.pi*731*t)+.004*rng.standard_normal(length),
        .11*np.sin(2*np.pi*3173*t)-.04*np.sin(2*np.pi*731*t)+.004*rng.standard_normal(length),
    ]).astype(np.float32).astype(np.float64)
    outputs = {}
    for name, mode, events in (("soft", 0, None), ("hard", 1, None),
                               ("switch", 0, {1280: 1, 1792: 0})):
        outputs[name] = hw.render(source, fs=fs, mode=mode, events=events,
                                  chunks=(17, 480, 1, 129))[0]

    window_sum = float(np.sum(hw.sqrt_hann(hw.N)))
    target = Path("test/spectral_hard_wola_fixtures.h")
    text = f"""// Generated by proto/dump_spectral_hard_wola_fixtures.py. Do not edit.
// Our additive Hard approximation on legacy N1024/H256 sqrt-Hann WOLA.
#pragma once
#include <array>
#include <cstddef>

namespace spectralhardfix {{
constexpr double kSampleRate = {fs:.17g};
constexpr int kFftSize = {hw.N};
constexpr int kHop = {hw.HOP};
constexpr int kLatency = {hw.N};
constexpr double kAnalysisWindowSum = {window_sum:.17g};
constexpr std::size_t kInputLength = {length};
constexpr std::size_t kOutputLength = {length+hw.N};
constexpr int kSwitchHardAtInputSample = 1280; // internal H boundary
constexpr int kSwitchSoftAtInputSample = 1792; // latest mode, retained s1/y1

inline constexpr std::array<double, 2*kInputLength> kInput{{
    {numbers(source)}
}};
inline constexpr std::array<double, 2*kOutputLength> kSoft{{
    {numbers(outputs['soft'])}
}};
inline constexpr std::array<double, 2*kOutputLength> kHard{{
    {numbers(outputs['hard'])}
}};
inline constexpr std::array<double, 2*kOutputLength> kSwitch{{
    {numbers(outputs['switch'])}
}};
}} // namespace spectralhardfix
"""
    target.write_text(text)
    print(f"wrote {target} ({target.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
